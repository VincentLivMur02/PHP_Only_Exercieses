<?php

/*

Esercizio 8:

- Hai un capitale di 1000 euro che guadagna il 5% di interessi ogni anno. 
- Usando un ciclo while, calcola quanti anni ci vorranno per superare i 2000 euro. 
- Stampa il numero di anni alla fine.

*/

$capital = 1000;

while ($capital < 3) {
    echo $capital * 5 / 100;
    $capital++;
}

